export function cuzin_lang() {
  const salva = localStorage.getItem(LANG_KEY);
  if (salva === "pt" || salva === "en") return salva;
  return "pt";
}

export function set_cuzin_lang(lang) {
  localStorage.setItem(LANG_KEY, lang);
}

export function t(key) {
  const L = bagulho[cuzin_lang()] || bagulho.pt;
  return L[key] ?? bagulho.en[key] ?? key;
}

export function api_lang_tag() {
  return cuzin_lang() === "pt" ? "pt-br" : "en";
}
