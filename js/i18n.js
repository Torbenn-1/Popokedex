const LANGS = ["pt", "en", "ja"];

export function cuzin_lang() {
  const salva = localStorage.getItem(LANG_KEY);
  if (LANGS.includes(salva)) return salva;
  return "pt";
}

export function next_lang(cur = cuzin_lang()) {
  const i = LANGS.indexOf(cur);
  return LANGS[(i < 0 ? 0 : i + 1) % LANGS.length];
}

export function set_cuzin_lang(lang) {
  localStorage.setItem(LANG_KEY, lang);
}

export function t(key) {
  const L = bagulho[cuzin_lang()] || bagulho.pt;
  return L[key] ?? bagulho.en[key] ?? key;
}

export function api_lang_tag() {
  const lang = cuzin_lang();
  if (lang === "pt") return "pt-br";
  if (lang === "ja") return "ja";
  return "en";
}

export function html_lang_tag() {
  const lang = cuzin_lang();
  if (lang === "pt") return "pt-BR";
  if (lang === "ja") return "ja";
  return "en";
}
