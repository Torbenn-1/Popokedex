export function move_id(slug) {
  if (!slug) return 0;
  return MOVE_ID[String(slug).toLowerCase()] || 0;
}

export function item_id(slug, gen) {
  if (!slug) return 0;
  const k = String(slug).toLowerCase();
  if (gen <= 3) return ITEM_ID_G3[k] || 0;
  return ITEM_ID_G45[k] || 0;
}

export function nature_index(slug) {
  if (!slug) return 0;
  const v = NATURE_INDEX[String(slug).toLowerCase()];
  return v == null ? 0 : v;
}

export function gen1_internal_from_slug(slug) {
  return GEN1_SLUG_TO_INTERNAL[String(slug || "").toLowerCase()] || 0;
}
