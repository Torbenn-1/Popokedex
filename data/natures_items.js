export function nature_por_slug(slug) {
  return NATURES.find((n) => n.slug === slug) || null;
}

export function rotulo_nature(slug, lang = "pt") {
  const n = nature_por_slug(slug);
  if (!n) return "";
  const name = slug.charAt(0).toUpperCase() + slug.slice(1);
  if (!n.up) return name;
  const stat = (s) =>
    ({ atk: "Atk", def: "Def", spa: "SpA", spd: "SpD", spe: "Spe" }[s] || s);
  return `${name} (+${stat(n.up)} / −${stat(n.down)})`;
}

export function rotulo_item(slug) {
  if (!slug) return "";
  return String(slug)
    .split("-")
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(" ");
}
